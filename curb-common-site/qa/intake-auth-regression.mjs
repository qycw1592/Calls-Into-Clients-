import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source=await readFile(new URL('../auth.js',import.meta.url),'utf8');
const {createSessionClient}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const url='https://synthetic.supabase.co',publishableKey='synthetic-key';
let calls=0;
const pending=[];
const fetcher=(path,opts)=>{calls++;return new Promise(resolve=>pending.push({path,opts,resolve}));};
const reply=(id)=>({ok:true,json:async()=>({access_token:'synthetic-'+id,expires_in:60,user:{id}})});
const preview=createSessionClient({url,publishableKey,fetcher});
await assert.rejects(preview.signIn('test@example.invalid','synthetic'),/preview/);
assert.equal(calls,0);
const session=createSessionClient({url,publishableKey,fetcher,releaseEnabled:true});
let clears=0;session.onSignOut(()=>clears++);
const first=session.signIn('a@example.invalid','synthetic');
await session.signOut();
pending.shift().resolve(reply('a'));
await assert.rejects(first,/superseded/);
assert.throws(()=>session.accessToken(),/Sign in again/);
assert.equal(clears,1);
const old=session.signIn('a@example.invalid','synthetic');
const newer=session.signIn('b@example.invalid','synthetic');
const a=pending.shift(),b=pending.shift();
b.resolve(reply('b'));assert.deepEqual(await newer,{userId:'b'});
a.resolve(reply('a'));await assert.rejects(old,/superseded/);
assert.equal(session.accessToken(),'synthetic-b');
const logout=session.signOut();
assert.throws(()=>session.accessToken(),/Sign in again/);
assert.equal(clears,2);
const request=pending.shift();assert.match(request.path,/logout$/);
assert.equal(request.opts.headers.Authorization,'Bearer synthetic-b');
request.resolve({ok:true});await logout;
console.log('PASS: preview network gate, delayed login invalidation, latest login wins, synchronous shared sign-out, correct logout token');
